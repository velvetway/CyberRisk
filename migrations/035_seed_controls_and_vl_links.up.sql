-- ---------------------------------------------------------------
-- 2. Связи vl_category_controls по матрице из диплома
-- ---------------------------------------------------------------

INSERT INTO vl_category_controls (vl_category_id, control_id, coverage)
SELECT vlc.id, c.id, 1.0
FROM vl_categories vlc
CROSS JOIN controls c
WHERE
    -- VL1 нештатное ПО: антивирус + админка + защита от НСД
    (vlc.code = 'VL1' AND c.name IN ('Антивирус', 'Системы администрирования', 'Программная защита от НСД'))
    -- VL2 устаревшее ПО / эксплуатация уязвимостей: антивирус + админка + защита от НСД
    OR (vlc.code = 'VL2' AND c.name IN ('Антивирус', 'Системы администрирования', 'Программная защита от НСД'))
    -- VL3 недекларируемое ПО: антивирус + админка + защита от НСД
    OR (vlc.code = 'VL3' AND c.name IN ('Антивирус', 'Системы администрирования', 'Программная защита от НСД'))
    -- VL4 обход админом: административные политики + защита от НСД
    OR (vlc.code = 'VL4' AND c.name IN ('Системы администрирования', 'Программная защита от НСД'))
    -- VL5 носители: антивирус + админка + защита от НСД (контроль USB-устройств)
    OR (vlc.code = 'VL5' AND c.name IN ('Антивирус', 'Системы администрирования', 'Программная защита от НСД'))
    -- VL6 открытые ОС / ЛВС: вся периметровая защита
    OR (vlc.code = 'VL6' AND c.name IN ('Межсетевой экран', 'Honeypot', 'Демилитаризованная зона',
                                        'Система обнаружения вторжений', 'Шифрование трафика', 'DDoS-фильтры'))
ON CONFLICT (vl_category_id, control_id) DO NOTHING;

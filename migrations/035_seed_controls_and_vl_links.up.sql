-- Сидим каталог методов противодействия (controls) и связь VL → control
-- строго по диплому ПТСЗИ (раздел «Методы противодействия» + матрица
-- «уязвимое звено ↔ метод противодействия»).
--
-- 11 контролей: A, FW, HP, DZ, IDS, AD, R, L, TE, DS, DD.
-- Связи берутся из таблицы соответствия в дипломе:
--   VL1 (нештатное ПО)              → A, AD, L
--   VL2 (устаревшее ПО / уязвимости)→ A, AD, L
--   VL3 (недекларируемое ПО)        → A, AD, L
--   VL4 (обход админом)             → AD, L
--   VL5 (носители)                  → A, AD, L
--   VL6 (открытые ОС / отсутствие СЗИ ЛВС) → FW, HP, DZ, IDS, TE, DD
--
-- Имена контролей — короткие («Антивирус», «Межсетевой экран» и т.п.) —
-- то, что ожидает увидеть оператор в UI. Поле name UNIQUE → ON CONFLICT.
--
-- Идемпотентно: повторный запуск ничего не меняет (UNIQUE name + ON CONFLICT).

-- ---------------------------------------------------------------
-- 1. Каталог controls
-- ---------------------------------------------------------------

INSERT INTO controls (name, control_type_id, description) VALUES
    ('Антивирус',                       1, 'Сигнатурно-эвристическая защита от вредоносного ПО (A)'),
    ('Межсетевой экран',                1, 'Фильтрация сетевого трафика на периметре и между сегментами (FW)'),
